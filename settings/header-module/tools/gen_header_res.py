#!/usr/bin/env python3
"""Generate the LSPosed Settings module's res/values from the ztmetro design tokens.

Single source of truth: repo/design/tokens/ztmetro.tokens.json.  Nothing in this
module hard-codes a colour, a type size or a layout height twice: this script
writes them into res/values/metro_header_{colors,dimens,styles}.xml and the Java
code only reads the generated resource ids.

The values that are *not* in the token file are properties of this Android
module (which page block wins over which stock widget), not of the C shell.
They live in MODULE_SPEC below with an explicit origin, exactly like the tokens
do.  The generator refuses to run if a token or a spec entry lost its origin.

    python3 tools/gen_header_res.py            # write the files
    python3 tools/gen_header_res.py --check    # exit 1 if the files are stale
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE_DIR = os.path.dirname(HERE)
REPO_DIR = os.path.dirname(os.path.dirname(MODULE_DIR))  # settings/header-module -> repo
TOKENS_PATH = os.path.join(REPO_DIR, "design", "tokens", "ztmetro.tokens.json")
OUT_DIR = os.path.join(MODULE_DIR, "res", "values")

GENERATED = """<!-- GENERATED by settings/header-module/tools/gen_header_res.py
     from design/tokens/ztmetro.tokens.json and the module spec in that script.
     Do not edit by hand: run the generator instead. -->
"""

MODULE_SECTION = GENERATED + "<resources>\n"


def fail(msg):
    sys.stderr.write("gen_header_res: %s\n" % msg)
    sys.exit(2)


def read_tokens():
    with open(TOKENS_PATH, "r", encoding="utf-8") as handle:
        return json.load(handle)


def ramp(tokens, name):
    for entry in tokens["type"]["ramp"]:
        if entry.get("name") == name:
            return entry
    fail("type.ramp has no %r entry" % name)


def module_spec(tokens):
    """Android-module values that have no C counterpart, each with its origin."""
    caption = ramp(tokens, "caption")
    header = tokens["type"]["header"]

    return {
        "header_height_dp": (
            tokens["metrics"]["header_height_dp"],
            "metrics.header_height_dp (%s; ZMC_HEADER_H 104) — the ztmeteo page "
            "block: caps label + 48 sp title + subtitle, status bar excluded (the "
            "status-bar inset is added on the homepage only, see HeaderBinder)"
            % tokens["metrics"]["header_height_dp"],
        ),
        "header_title_sp": (
            header["title_size_sp"],
            "type.header.title_size_sp (%s) = type.ramp[page_title]"
            % header["title_size_sp"],
        ),
        "header_label_sp": (
            header["subtitle_size_sp"],
            "type.header.subtitle_size_sp (%s) = type.ramp[caption_caps] (the caps "
            "app/page label above the title)" % header["subtitle_size_sp"],
        ),
        "header_label_spacing": (
            0.08,
            "module spec: 0.08 em letter-spacing on the ALL-CAPS label (WP caps "
            "tracking; Android TextView.letterSpacing unit is em)",
        ),
        "subtitle_sp": (
            caption["size_sp_at_density_1x"],
            "type.ramp[caption].size_sp_at_density_1x (%s)"
            % caption["size_sp_at_density_1x"],
        ),
        "subtitle_alpha": (
            0.70,
            "module spec: label and subtitle at 70% opacity (secondary text on "
            "black; the reference labels measure 0.70 white)",
        ),
        "padding_h_dp": (
            24,
            "module spec: 24 dp page margin for the header block and the flat "
            "preference rows (deliverable; note tokens.metrics.page_margin_dp is "
            "16 dp for the C shell at 360 dp — the Settings page uses the wider "
            "Android margin so the 48 sp title is not edge-to-edge)",
        ),
        "bottom_bar_height_dp": (
            tokens["metrics"]["nav_bar_height_dp"],
            "metrics.nav_bar_height_dp (%s; ztmetro.c:130 NAV_BAR_H 40)"
            % tokens["metrics"]["nav_bar_height_dp"],
        ),
        "bottom_bar_label_sp": (
            11,
            "module spec: 11 sp ALL-CAPS 'ZRN' in the 40 dp bar (README requirement; "
            "one step below type.ramp[caption_caps] 11.5 so it optically centres in "
            "40 dp)",
        ),
        "button_pressed_alpha": (
            0.24,
            "module spec: pressed fill of the bottom-bar glyph buttons — "
            "24% of color.accent.base (subtle Metro press state on black)",
        ),
        "bottom_bar_glyph_dp": (
            24,
            "module spec: 24 dp back/search glyphs inside the 40 dp bar (Android "
            "minimum icon size; the whole 40x40 dp cell is the touch target)",
        ),
    }


def num(value):
    if float(value).is_integer():
        return str(int(value))
    return ("%.3f" % float(value)).rstrip("0").rstrip(".")


def with_alpha(hex_rgb, alpha):
    """#RRGGBB + alpha -> #AARRGGBB."""
    a = int(alpha * 255 + 0.5)
    return "#%02X%s" % (a, hex_rgb.lstrip("#").upper())


def build(tokens):
    neutrals = tokens["color"]["neutrals"]
    accent = tokens["color"]["accent"]
    base = accent["base"].upper()
    white = neutrals["text_primary"].upper()
    black = neutrals["black"].upper()
    families = tokens["type"]["families"]["android_fallback"]

    spec = module_spec(tokens)
    for key, (_, origin) in spec.items():
        if not str(origin).strip():
            fail("module spec %s has no origin" % key)

    faded = with_alpha(white, spec["subtitle_alpha"][0])

    colors = MODULE_SECTION + (
        "  <!-- color.neutrals.black -->\n"
        '  <color name="metro_header_bg">%s</color>\n'
        "  <!-- color.neutrals.text_primary -->\n"
        '  <color name="metro_header_title">%s</color>\n'
        "  <!-- color.neutrals.text_primary at %s alpha (%s) -->\n"
        '  <color name="metro_header_label">%s</color>\n'
        "  <!-- color.neutrals.text_primary at %s alpha (%s) -->\n"
        '  <color name="metro_header_subtitle">%s</color>\n'
        "  <!-- color.accent.base — kept for the pressed state of the bar buttons; "
        "never used as a fill -->\n"
        '  <color name="metro_accent">%s</color>\n'
        "  <!-- color.accent.base at %s alpha (%s) -->\n"
        '  <color name="metro_accent_pressed">%s</color>\n'
        "  <!-- color.neutrals.black -->\n"
        '  <color name="metro_bottom_bar_bg">%s</color>\n'
        "  <!-- color.neutrals.text_primary -->\n"
        '  <color name="metro_bottom_bar_text">%s</color>\n'
        "</resources>\n"
    ) % (black, white, num(spec["subtitle_alpha"][0]), spec["subtitle_alpha"][1],
         faded, num(spec["subtitle_alpha"][0]), spec["subtitle_alpha"][1], faded,
         base, num(spec["button_pressed_alpha"][0]), spec["button_pressed_alpha"][1],
         with_alpha(base, spec["button_pressed_alpha"][0]), black, white)

    dimens = MODULE_SECTION + (
        "  <!-- %s -->\n"
        '  <dimen name="metro_header_height">%sdp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_header_label_size">%ssp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_header_title_size">%ssp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_header_subtitle_size">%ssp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_header_padding_h">%sdp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_bottom_bar_height">%sdp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_bottom_bar_label_size">%ssp</dimen>\n'
        "  <!-- %s -->\n"
        '  <dimen name="metro_bottom_bar_glyph">%sdp</dimen>\n'
        "</resources>\n"
    ) % (spec["header_height_dp"][1], num(spec["header_height_dp"][0]),
         spec["header_label_sp"][1], num(spec["header_label_sp"][0]),
         spec["header_title_sp"][1], num(spec["header_title_sp"][0]),
         spec["subtitle_sp"][1], num(spec["subtitle_sp"][0]),
         spec["padding_h_dp"][1], num(spec["padding_h_dp"][0]),
         spec["bottom_bar_height_dp"][1], num(spec["bottom_bar_height_dp"][0]),
         spec["bottom_bar_label_sp"][1], num(spec["bottom_bar_label_sp"][0]),
         spec["bottom_bar_glyph_dp"][1], num(spec["bottom_bar_glyph_dp"][0]))

    # Type faces: the tokens map the Segoe stack onto the system families because no
    # font file is shipped (design/tokens/README.md, "No font files are shipped").
    styles = MODULE_SECTION + (
        '  <style name="MetroHeaderLabel">\n'
        '    <item name="android:textSize">@dimen/metro_header_label_size</item>\n'
        '    <item name="android:textColor">@color/metro_header_label</item>\n'
        '    <item name="android:fontFamily">sans-serif-medium</item>\n'
        '    <item name="android:letterSpacing">%s</item>\n'
        '    <item name="android:includeFontPadding">false</item>\n'
        '    <item name="android:maxLines">1</item>\n'
        '    <item name="android:ellipsize">end</item>\n'
        '  </style>\n'
        '  <style name="MetroHeaderTitle">\n'
        '    <item name="android:textSize">@dimen/metro_header_title_size</item>\n'
        '    <item name="android:textColor">@color/metro_header_title</item>\n'
        '    <item name="android:fontFamily">sans-serif-light</item>\n'
        '    <item name="android:includeFontPadding">false</item>\n'
        '    <item name="android:maxLines">1</item>\n'
        '    <item name="android:ellipsize">end</item>\n'
        '  </style>\n'
        '  <style name="MetroHeaderSubtitle">\n'
        '    <item name="android:textSize">@dimen/metro_header_subtitle_size</item>\n'
        '    <item name="android:textColor">@color/metro_header_subtitle</item>\n'
        '    <item name="android:fontFamily">sans-serif</item>\n'
        '    <item name="android:includeFontPadding">false</item>\n'
        '    <item name="android:maxLines">1</item>\n'
        '    <item name="android:ellipsize">end</item>\n'
        '  </style>\n'
        '  <style name="MetroBottomBarLabel">\n'
        '    <item name="android:textSize">@dimen/metro_bottom_bar_label_size</item>\n'
        '    <item name="android:textColor">@color/metro_bottom_bar_text</item>\n'
        '    <item name="android:fontFamily">sans-serif</item>\n'
        '    <item name="android:letterSpacing">%s</item>\n'
        '    <item name="android:includeFontPadding">false</item>\n'
        '    <item name="android:gravity">center</item>\n'
        '  </style>\n'
        '  <!-- %s -->\n'
        "</resources>\n"
    ) % (num(spec["header_label_spacing"][0]), num(spec["header_label_spacing"][0]),
         families)

    return {
        "metro_header_colors.xml": colors,
        "metro_header_dimens.xml": dimens,
        "metro_header_styles.xml": styles,
    }


def main(argv):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="verify the committed files instead of writing them")
    args = parser.parse_args(argv)

    tokens = read_tokens()
    outputs = build(tokens)
    os.makedirs(OUT_DIR, exist_ok=True)

    stale = []
    for name, content in outputs.items():
        path = os.path.join(OUT_DIR, name)
        if args.check:
            try:
                with open(path, "r", encoding="utf-8") as handle:
                    current = handle.read()
            except OSError:
                current = None
            if current != content:
                stale.append(name)
        else:
            with open(path, "w", encoding="utf-8") as handle:
                handle.write(content)
            print("wrote %s" % os.path.relpath(path, REPO_DIR))

    if stale:
        sys.stderr.write("stale generated resources: %s (run the generator)\n"
                         % ", ".join(stale))
        return 1
    if args.check:
        print("generated resources are up to date")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
