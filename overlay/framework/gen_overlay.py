#!/usr/bin/env python3
"""Generate the ztmetro framework-res RRO values from ztmetro.tokens.json.

Target package: "android" (framework-res), AOSP android-16.0.0_r3.

Writes, next to this script:

  res/values/ztmetro_colors.xml    accent + Material You dynamic-colour seeds
  res/values/ztmetro_dimens.xml    square-corner radii, app-bar height
  res/values/ztmetro_bools.xml     Metro sentence case instead of ALL CAPS
  res/values/ztmetro_styles.xml    TextAppearance.Material / StatusBar / Notification

Every resource *name* below was grepped against the AOSP tag's
core/res/res/values/*.xml (see evidence/framework-rro/REPORT.md for the
name -> file:line table).  A name that does not exist in the target is silently
ignored by idmap2, so adding names here is only allowed together with a
verification entry.

Every resource *value* is derived from the token file except where a comment
says "framework constant" (the ripple alpha, which ztmetro does not model).

No dependencies, no network.  Usage:

    python3 gen_overlay.py [--tokens PATH] [--out DIR] [--check]
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TOKENS = os.path.normpath(
    os.path.join(HERE, "..", "..", "design", "tokens", "ztmetro.tokens.json"))

HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- GENERATED by overlay/framework/gen_overlay.py from design/tokens/ztmetro.tokens.json.\n"
    "     Do not edit by hand. Resource names verified against AOSP android-16.0.0_r3\n"
    "     core/res/res/values (see evidence/framework-rro/REPORT.md). -->\n"
)


def load(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def num(value):
    """Shortest honest decimal for an Android resource."""
    if float(value).is_integer():
        return str(int(value))
    return ("%.4f" % float(value)).rstrip("0").rstrip(".")


def argb(hex_color):
    return "#FF" + hex_color.lstrip("#").upper()


def family(weight):
    """Metro family -> system face (design/tokens/README.md, "derived [E]")."""
    if weight <= 350:
        return "sans-serif-light"
    if weight >= 500:
        return "sans-serif-medium"
    return "sans-serif"


# --- colours -------------------------------------------------------------
# (resource name, token key under color.accent)
ACCENT_COLORS = (
    ("accent_device_default_light", "base"),
    ("accent_device_default", "base"),
    ("accent_device_default_dark", "light1"),
    ("accent_material_light", "base"),
    ("accent_material_dark", "light1"),
)

# Material You seeds.  The 13-tone scale's plain names are defined in
# colors_dynamic.xml and point at the *_light / *_dark baseline colours in
# colors.xml, so both families are overridden with the same tone values.
DYNAMIC_TONES = (
    ("system_accent1_100", "light2"),
    ("system_accent1_200", "light1"),
    ("system_accent1_500", "base"),
    ("system_accent1_600", "dark1"),
    ("system_accent1_700", "dark2"),
)

RIPPLE_ALPHA = 0x1F  # framework constant: highlight_alpha_material_light/dark = 0.12

# Quick Settings tile fills.  SystemUI's Theme.SystemUI.QuickSettings sets
# shadeActive/shadeInactive to @androidprv:color/customColorShade* (unreachable
# from a com.android.systemui overlay), so the framework colours behind them are
# overridden here.  No "customColorShadePressed" exists at API 36: the pressed
# state is the ripple (ripple_material_light/dark, already accent-tinted).
# (name, colour source) — "accent:<key>" / "neutrals:<key>" / literal #RRGGBB
SHADE_COLORS = (
    ("customColorShadeActive", "accent:base"),
    ("customColorShadeInactive", "neutrals:surface_off"),
    ("customColorShadeDisabled", "accent:dark2"),
    ("customColorOnShadeActive", "accent:foreground_on_accent"),
    # stock #334671 (dark navy) is unreadable on the cobalt tile; the framework's
    # existing light shade tone keeps secondary labels legible (colors.xml:688)
    ("customColorOnShadeActiveVariant", "#D9E2FF"),
)

# --- dimensions ----------------------------------------------------------
# (resource name, value, why)
DIMENS = (
    ("config_buttonCornerRadius", "0dp",
     "config.xml; Metro tiles/controls are square (tokens metrics.corner_radius_dp 0)"),
    ("config_dialogCornerRadius", "0dp",
     "config.xml; square dialogs"),
    ("config_bottomDialogCornerRadius", "0dp",
     "config.xml; square bottom sheets"),
    ("config_progressBarCornerRadius", "0dp",
     "config.xml; square progress bars (stock 1000dp = pill)"),
    ("control_corner_material", "0dp",
     "dimens_material.xml; Material theme buttonCornerRadius + control shapes"),
    ("dialog_corner_radius", "0dp",
     "dimens.xml; Material dialog window background"),
    ("action_bar_default_height_material", "{action_bar}dp",
     "dimens_material.xml; Metro min touch target (tokens metrics.min_touch_target_dp)"),
)

# --- bools ---------------------------------------------------------------
BOOLS = (
    ("config_actionMenuItemAllCaps", "false",
     "config.xml; Metro is sentence case - only caption_caps is ALL CAPS"),
    ("config_buttonTextAllCaps", "false",
     "config.xml; Metro is sentence case - only caption_caps is ALL CAPS"),
)

# --- text appearances ----------------------------------------------------
# (style, parent stock style, ramp token, colour, all_caps)
# colour is an Android resource/attr reference or a literal #AARRGGBB.
TEXT_APPEARANCES = (
    ("TextAppearance.Material", "TextAppearance", "body",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Display4", "TextAppearance.Material", "display_large",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Display3", "TextAppearance.Material", "display",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Display2", "TextAppearance.Material", "page_title",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Display1", "TextAppearance.Material", "list_title",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Headline", "TextAppearance.Material", "app_list_title",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Title", "TextAppearance.Material", "subtitle",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Subhead", "TextAppearance.Material", "body_large",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Body1", "TextAppearance.Material", "body",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Body2", "TextAppearance.Material", "body",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Caption", "TextAppearance.Material", "caption",
     "?android:attr/textColorSecondary", False),
    ("TextAppearance.Material.Button", "TextAppearance.Material", "body",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Menu", "TextAppearance.Material", "body_large",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Widget.ActionBar.Title", "TextAppearance.Material", "subtitle",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Widget.ActionBar.Subtitle", "TextAppearance.Material",
     "caption_caps", "?android:attr/textColorSecondary", True),
    ("TextAppearance.Material.Notification", "TextAppearance.Material", "body",
     "?android:attr/textColorSecondary", False),
    ("TextAppearance.Material.Notification.Title", "TextAppearance.Material", "body_large",
     "?android:attr/textColorPrimary", False),
    ("TextAppearance.Material.Notification.Line2", "TextAppearance.Material", "caption",
     "?android:attr/textColorSecondary", False),
    ("TextAppearance.StatusBar.EventContent", "TextAppearance.Material", "body",
     "#999999", False),
    ("TextAppearance.StatusBar.EventContent.Title", "TextAppearance.Material", "body_large",
     "#FFFFFF", False),
)

BASE_EXTRA_ITEMS = (
    ("textColorHint", "?android:attr/textColorHint"),
    ("textColorHighlight", "?android:attr/textColorHighlight"),
    ("textColorLink", "?android:attr/textColorLink"),
)


def accent_value(token_key, accent):
    """Accent colour as #AARRGGBB."""
    return argb(accent[token_key])


def emit_colors(tokens):
    accent = tokens["color"]["accent"]
    lines = [HEADER, "<resources>", "",
             "    <!-- accent: one cobalt, #0050EF base (color.accent.base) -->"]
    for name, key in ACCENT_COLORS:
        lines.append('    <color name="%s">%s</color>' % (name, accent_value(key, accent)))

    lines.extend([
        "",
        "    <!-- ripples: accent at 12% (framework ripple alpha, not a ztmetro token) -->",
    ])
    for name in ("ripple_material_light", "ripple_material_dark"):
        base = accent["base"].lstrip("#").upper()
        lines.append('    <color name="%s">#%02X%s</color>' % (name, RIPPLE_ALPHA, base))

    lines.extend([
        "",
        "    <!-- Material You seeds: plain names (colors_dynamic.xml) + the",
        "         *_light / *_dark baselines they point at (colors.xml) -->",
    ])
    for name, key in DYNAMIC_TONES:
        value = accent_value(key, accent)
        lines.append('    <color name="%s">%s</color>' % (name, value))
        for suffix in ("light", "dark"):
            lines.append('    <color name="%s_%s">%s</color>' % (name, suffix, value))

    lines.extend([
        "",
        "    <!-- Quick Settings tile fills (private framework colours behind",
        "         @androidprv:color/customColorShade* used by SystemUI) -->",
    ])
    accent = tokens["color"]["accent"]
    neutrals = tokens["color"]["neutrals"]
    for name, source in SHADE_COLORS:
        if source.startswith("accent:"):
            value = argb(accent[source.split(":", 1)[1]])
        elif source.startswith("neutrals:"):
            value = argb(neutrals[source.split(":", 1)[1]])
        else:
            value = argb(source)
        lines.append('    <color name="%s">%s</color>' % (name, value))

    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def emit_dimens(tokens):
    action_bar = num(tokens["metrics"]["min_touch_target_dp"])
    lines = [HEADER, "<resources>"]
    for name, value, why in DIMENS:
        lines.append("")
        lines.append("    <!-- %s -->" % why)
        lines.append('    <dimen name="%s">%s</dimen>' % (name, value.format(action_bar=action_bar)))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def emit_bools(tokens):
    lines = [HEADER, "<resources>"]
    for name, value, why in BOOLS:
        lines.append("")
        lines.append("    <!-- %s -->" % why)
        lines.append('    <bool name="%s">%s</bool>' % (name, value))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def ramp_map(tokens):
    return {entry["name"]: entry for entry in tokens["type"]["ramp"]}


def ramp_items(entry, color, all_caps, base=False):
    size = float(entry["size_sp_at_density_1x"])
    multiplier = float(entry["line_height"]) / size
    items = [("textColor", color)]
    if base:
        items.extend(BASE_EXTRA_ITEMS)
    items.extend([
        ("textSize", "%ssp" % num(size)),
        ("fontFamily", family(entry["semibold_weight"])),
        ("lineSpacingMultiplier", num(multiplier)),
        # ztmetro draws text with Pango's default (zero) tracking; the token
        # file has no letter-spacing field, so zero is the honest value.
        ("letterSpacing", "0"),
        ("textAllCaps", "true" if all_caps else "false"),
    ])
    return items


def style_block(name, parent, items):
    lines = ['    <style name="%s" parent="@android:style/%s">' % (name, parent)]
    for key, value in items:
        lines.append('        <item name="android:%s">%s</item>' % (key, value))
    lines.append("    </style>")
    return lines


def emit_styles(tokens):
    ramp = ramp_map(tokens)
    lines = [HEADER, "<resources>"]
    for index, (name, parent, ramp_name, color, all_caps) in enumerate(TEXT_APPEARANCES):
        entry = ramp[ramp_name]
        if index:
            lines.append("")
        lines.append("    <!-- %s: %s, %s -->" % (
            ramp_name, num(entry["size_sp_at_density_1x"]),
            "ALL CAPS" if all_caps else "sentence case"))
        lines.extend(style_block(
            name, parent, ramp_items(entry, color, all_caps, base=(index == 0))))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="gen_overlay.py",
        description="Generate framework-res RRO values from ztmetro.tokens.json.")
    parser.add_argument("--tokens", default=DEFAULT_TOKENS,
                        help="token file (default: design/tokens/ztmetro.tokens.json)")
    parser.add_argument("--out", default=HERE,
                        help="overlay source directory to write res/values into (default: this script's directory)")
    parser.add_argument("--check", action="store_true",
                        help="generate into a temp dir and fail if the committed files differ")
    args = parser.parse_args(argv)

    tokens = load(args.tokens)
    files = {
        os.path.join(args.out, "res", "values", "ztmetro_colors.xml"): emit_colors(tokens),
        os.path.join(args.out, "res", "values", "ztmetro_dimens.xml"): emit_dimens(tokens),
        os.path.join(args.out, "res", "values", "ztmetro_bools.xml"): emit_bools(tokens),
        os.path.join(args.out, "res", "values", "ztmetro_styles.xml"): emit_styles(tokens),
    }

    if args.check:
        stale = []
        for path, text in files.items():
            try:
                with open(path, "r", encoding="utf-8") as handle:
                    if handle.read() != text:
                        stale.append(path)
            except FileNotFoundError:
                stale.append(path)
        if stale:
            sys.stderr.write("generated resources are stale:\n")
            for path in stale:
                sys.stderr.write("  - %s\n" % path)
            return 1
        print("generated resources are up to date")
        return 0

    for path, text in files.items():
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w", encoding="utf-8", newline="\n") as handle:
            handle.write(text)
    print("wrote %d files under %s" % (len(files), os.path.join(args.out, "res", "values")))
    return 0


if __name__ == "__main__":
    sys.exit(main())
