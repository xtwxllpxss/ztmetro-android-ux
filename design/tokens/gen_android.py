#!/usr/bin/env python3
"""Emit Android resources from ztmetro.tokens.json.

Reads the single source of truth next to this script and writes:

  OUT/res/values/metro_colors.xml    colour resources
  OUT/res/values/metro_dimens.xml    dp sizes, integers, motion durations
  OUT/res/values/metro_styles.xml    TextAppearance entries + framework-res overlay map sample
  OUT/overlay/metro_overlay.xml      compile-ready sample overlay for framework-res
  OUT/java/MetroTokens.java          launcher constants snippet

No third-party packages, no network. Every number the JSON calls a metric or a
duration must carry an origin, and the script refuses to run otherwise.

CLI (also in --help):

    python3 gen_android.py --out DIR

Author: ztmetro-android-ux contributors. MIT (see repo/LICENSE).
"""

import argparse
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_TOKENS = os.path.join(HERE, "ztmetro.tokens.json")

# Groups whose every key must appear in their "_origins" map.
ORIGIN_GROUPS = (
    ("color", "accent"),
    ("color", "neutrals"),
    ("color", "status"),
    ("color", "chrome"),
    ("metrics", None),
    ("motion", None),
)

XML_HEADER = (
    '<?xml version="1.0" encoding="utf-8"?>\n'
    "<!-- GENERATED by design/tokens/gen_android.py from ztmetro.tokens.json.\n"
    "     Do not edit by hand: change the JSON and regenerate.\n"
    "     Values are facts about ztmetro's UI; see design/tokens/README.md. -->\n"
)


def load_tokens(path):
    with open(path, "r", encoding="utf-8") as handle:
        return json.load(handle)


def check_origins(tokens):
    """Return a list of human-readable provenance gaps."""
    problems = []

    def check_group(group, label):
        origins = group.get("_origins", {})
        for key, value in group.items():
            if key.startswith("_"):
                continue
            if key not in origins or not str(origins[key]).strip():
                problems.append("%s.%s has no _origins entry" % (label, key))
            if isinstance(value, int) and not isinstance(value, bool) and value < 0:
                problems.append("%s.%s is negative" % (label, key))

    for top, sub in ORIGIN_GROUPS:
        node = tokens[top]
        if sub is not None:
            check_group(node[sub], "%s.%s" % (top, sub))
        else:
            check_group(node, top)

    ramp = tokens["type"]["ramp"]
    for entry in ramp:
        for field in ("semibold_weight", "size_sp_at_density_1x", "line_height"):
            if field not in entry:
                problems.append("type.ramp[%s] lacks %s" % (entry.get("name"), field))
        for field in ("origin", "line_height_origin"):
            if not str(entry.get(field, "")).strip():
                problems.append("type.ramp[%s] lacks %s" % (entry.get("name"), field))

    header = tokens["type"]["header"]
    header_origins = header.get("origin", {})
    for field in ("title_size_sp", "subtitle_size_sp", "gap"):
        if field not in header:
            problems.append("type.header lacks %s" % field)
        elif field not in header_origins:
            problems.append("type.header.%s has no origin" % field)

    for group in ("accent", "neutrals", "status", "chrome"):
        for key, value in tokens["color"][group].items():
            if key.startswith("_") or isinstance(value, float):
                continue  # scrim_alpha is an alpha, not a colour
            if not isinstance(value, str) or not value.startswith("#") or len(value) != 7:
                problems.append("color.%s.%s is not #RRGGBB: %r" % (group, key, value))
    return problems


def num(value):
    """Shortest honest decimal for an Android resource."""
    if isinstance(value, bool):
        raise TypeError("boolean where a number was expected")
    if float(value).is_integer():
        return str(int(value))
    return ("%.3f" % float(value)).rstrip("0").rstrip(".")


def color_name(group, key):
    if group == "accent":
        if key == "base":
            return "metro_accent"
        if key == "foreground_on_accent":
            return "metro_on_accent"
        return "metro_accent_" + key
    if group == "neutrals":
        return "metro_" + key
    return "metro_%s_%s" % (group, key)


def android_argb(hex_color):
    return "#FF" + hex_color.lstrip("#").upper()


def color_rows(tokens):
    rows = []
    for group in ("accent", "neutrals", "status", "chrome"):
        rows.append("")
        rows.append("    <!-- %s -->" % group)
        for key, value in tokens["color"][group].items():
            if key.startswith("_") or isinstance(value, float):
                continue
            rows.append('    <color name="%s">%s</color>' % (color_name(group, key), android_argb(value)))
    return rows


def emit_colors(tokens):
    lines = [XML_HEADER, "<resources>"]
    lines.extend(color_rows(tokens))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


def emit_dimens(tokens):
    metrics = tokens["metrics"]
    motion = tokens["motion"]
    lines = [XML_HEADER, "<resources>", "", "    <!-- metrics (dp at the 360x640 dp reference; see metrics._origins) -->"]
    for key, value in metrics.items():
        if key.startswith("_"):
            continue
        if key == "start_columns":
            lines.append('    <integer name="metro_start_columns">%s</integer>' % num(value))
        elif key.endswith("_dp"):
            lines.append('    <dimen name="metro_%s">%sdp</dimen>' % (key[:-3], num(value)))
        else:
            lines.append('    <integer name="metro_%s">%s</integer>' % (key, num(value)))

    lines.append("")
    lines.append("    <!-- motion durations; tilt degrees and press sink live in MetroTokens.java -->")
    for key, value in motion.items():
        if key.startswith("_") or not key.endswith("_ms"):
            continue
        lines.append('    <integer name="metro_motion_%s">%s</integer>' % (key, num(value)))
    lines.append('    <dimen name="metro_motion_tilt_lift">%sdp</dimen>' % num(motion["tilt_lift_dp"]))
    lines.append("</resources>")
    return "\n".join(lines) + "\n"


FAMILY_ANDROID = {
    "display": "sans-serif-light",
    "light": "sans-serif-light",
    "body": "sans-serif",
    "semibold": "sans-serif-medium",
}

# ramp name -> (Android style suffix, colour resource)
STYLE_MAP = (
    ("page_title", "PageTitle", "metro_text_primary"),
    ("list_title", "ListTitle", "metro_text_primary"),
    ("subtitle", "Subtitle", "metro_text_primary"),
    ("body", "Body", "metro_text_primary"),
    ("caption", "Caption", "metro_text_secondary"),
    ("caption_caps", "Caps", "metro_text_primary"),
    ("display", "Display", "metro_text_primary"),
    ("display_large", "DisplayLarge", "metro_text_primary"),
)


def ramp_by_name(tokens):
    return {entry["name"]: entry for entry in tokens["type"]["ramp"]}


def emit_styles(tokens):
    ramp = ramp_by_name(tokens)
    lines = [
        XML_HEADER,
        "<resources>",
        "",
        "    <!-- TextAppearance entries. Semilight/Light have no Android face: they map",
        "         to sans-serif-light, Semibold to sans-serif-medium (derived [E]).",
        "         lineSpacingMultiplier = line_height / size, so the C line rhythm survives. -->",
    ]
    for ramp_name, suffix, text_color in STYLE_MAP:
        entry = ramp[ramp_name]
        size = float(entry["size_sp_at_density_1x"])
        multiplier = float(entry["line_height"]) / size
        lines.extend([
            "",
            "    <!-- %s: %s -->" % (entry["name"], entry["usage"]),
            '    <style name="TextAppearance.Metro.%s" parent="android:TextAppearance">' % suffix,
            '        <item name="android:fontFamily">%s</item>' % FAMILY_ANDROID["display"]
            if entry["semibold_weight"] <= 350 else
            '        <item name="android:fontFamily">%s</item>' % (
                FAMILY_ANDROID["semibold"] if entry["semibold_weight"] >= 500 else FAMILY_ANDROID["body"]),
            '        <item name="android:textSize">%ssp</item>' % num(size),
            '        <item name="android:textColor">@color/%s</item>' % text_color,
            '        <item name="android:lineSpacingMultiplier">%.3f</item>' % multiplier,
        ])
        if ramp_name == "caption_caps":
            lines.append('        <item name="android:textAllCaps">true</item>')
        lines.append("    </style>")

    accent = tokens["color"]["accent"]
    lines.extend([
        "",
        "    <!-- FRAMEWORK-RES OVERLAY MAP (sample). Build it as a separate overlay APK",
        "         against target package android; never merge it into the launcher. The",
        "         compile-ready copy is overlay/metro_overlay.xml.",
        '         <item name="colorAccent" type="color">%s</item>' % android_argb(accent["base"]),
        '         <item name="colorPrimary" type="color">%s</item>' % android_argb(accent["base"]),
        '         <item name="system_accent1_500" type="color">%s</item>' % android_argb(accent["base"]),
        '         <item name="system_accent1_200" type="color">%s</item>' % android_argb(accent["light1"]),
        '         <item name="system_accent1_100" type="color">%s</item>' % android_argb(accent["light2"]),
        '         <item name="system_accent1_600" type="color">%s</item>' % android_argb(accent["dark1"]),
        '         <item name="system_accent1_700" type="color">%s</item>' % android_argb(accent["dark2"]),
        '         <item name="textAppearanceLarge" type="style">@style/TextAppearance.Metro.PageTitle</item>',
        '         <item name="textAppearanceMedium" type="style">@style/TextAppearance.Metro.Body</item>',
        '         <item name="textAppearanceSmall" type="style">@style/TextAppearance.Metro.Caps</item>',
        "    -->",
        "</resources>",
    ])
    return "\n".join(lines) + "\n"


def emit_overlay(tokens):
    accent = tokens["color"]["accent"]

    def hex_item(name, key):
        return '    <item name="%s" type="color">%s</item>' % (name, android_argb(accent[key]))

    lines = [
        XML_HEADER,
        "<!-- Sample RRO/overlay map for target package \"android\". Build it in its own",
        "     overlay APK (aapt2 link, target package android, auto-add-overlay); do NOT",
        "     merge this file into the launcher. Colours are inlined so the overlay needs no",
        "     shared colour resources; the TextAppearance styles it points at must be copied",
        "     into the overlay package (see design/tokens/README.md, overlay recipe).",
        "     Values come from color.accent in ztmetro.tokens.json. -->",
        "<resources>",
        "",
        hex_item("colorAccent", "base"),
        hex_item("colorPrimary", "base"),
        # Android 12+ dynamic-colour seeds
        hex_item("system_accent1_500", "base"),
        hex_item("system_accent1_100", "light2"),
        hex_item("system_accent1_200", "light1"),
        hex_item("system_accent1_600", "dark1"),
        hex_item("system_accent1_700", "dark2"),
        "",
        '    <item name="textAppearanceLarge" type="style">@style/TextAppearance.Metro.PageTitle</item>',
        '    <item name="textAppearanceMedium" type="style">@style/TextAppearance.Metro.Body</item>',
        '    <item name="textAppearanceSmall" type="style">@style/TextAppearance.Metro.Caps</item>',
        "</resources>",
    ]
    return "\n".join(lines) + "\n"


def emit_java(tokens):
    accent = tokens["color"]["accent"]
    metrics = tokens["metrics"]
    motion = tokens["motion"]
    ramp = ramp_by_name(tokens)
    header = tokens["type"]["header"]

    def argb(hex_color):
        return "0xFF" + hex_color.lstrip("#").upper()

    lines = [
        "// GENERATED by design/tokens/gen_android.py from ztmetro.tokens.json.",
        "// Do not edit by hand: change the JSON and regenerate.",
        "// Values are facts about ztmetro's UI; see design/tokens/README.md.",
        "",
        "import android.graphics.Color;",
        "",
        "/** ztmetro design tokens for the launcher. All dimensions are dp, text sp. */",
        "public final class MetroTokens {",
        "    private MetroTokens() {}",
        "",
        "    // ---- accent (color.accent) ----",
        '    public static final String ACCENT_HEX = "%s";' % accent["base"],
        "    public static final int ACCENT = Color.parseColor(ACCENT_HEX);",
        "    public static final int ACCENT_LIGHT1 = %s;" % argb(accent["light1"]),
        "    public static final int ACCENT_LIGHT2 = %s;" % argb(accent["light2"]),
        "    public static final int ACCENT_DARK1 = %s;" % argb(accent["dark1"]),
        "    public static final int ACCENT_DARK2 = %s;" % argb(accent["dark2"]),
        "    public static final int ON_ACCENT = %s;" % argb(accent["foreground_on_accent"]),
        "",
        "    // ---- surfaces and text (color.neutrals, color.chrome) ----",
    ]
    for group, prefix in (("neutrals", ""), ("status", "STATUS_"), ("chrome", "CHROME_")):
        for key, value in tokens["color"][group].items():
            if key.startswith("_"):
                continue
            name = prefix + key.upper()
            if isinstance(value, float):
                lines.append("    public static final float %s = %sf;" % (name, num(value)))
                continue
            lines.append("    public static final int %s = %s;" % (name, argb(value)))
    lines.extend([
        "",
        "    // ---- metrics (dp), from metrics in the JSON ----",
    ])
    for key, value in metrics.items():
        if key.startswith("_"):
            continue
        if key == "start_columns":
            lines.append("    public static final int START_COLUMNS = %s;" % num(value))
        else:
            const = key[:-3].upper() if key.endswith("_dp") else key.upper()
            lines.append("    public static final float %s_DP = %sf;" % (const, num(value)))
    lines.extend([
        "",
        "    // ---- type (sp at density 1x / fontScale 1.0) ----",
        "    public static final float HEADER_TITLE_SIZE_SP = %sf;" % num(header["title_size_sp"]),
        "    public static final float HEADER_CAPS_SIZE_SP = %sf;" % num(header["subtitle_size_sp"]),
        "    public static final float HEADER_GAP_DP = %sf;" % num(header["gap"]),
    ])
    for name, entry in sorted(ramp.items()):
        lines.append("    public static final float %s_SIZE_SP = %sf;" % (name.upper(), num(entry["size_sp_at_density_1x"])))
    lines.extend([
        "",
        "    // ---- motion (motion in the JSON) ----",
    ])
    for key, value in motion.items():
        if key.startswith("_"):
            continue
        if key.endswith("_ms"):
            lines.append("    public static final int %s = %s;" % (key.upper(), num(value)))
    lines.extend([
        "    public static final float TILT_DEG = %sf;" % num(motion["tilt_deg"]),
        "    public static final float TILT_LIFT_DP = %sf;" % num(motion["tilt_lift_dp"]),
        "    public static final float PRESS_SINK_FRACTION = %sf;" % num(motion["press_sink_fraction"]),
        "}",
    ])
    return "\n".join(lines) + "\n"


def write_file(path, text):
    directory = os.path.dirname(path)
    if directory:
        os.makedirs(directory, exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="\n") as handle:
        handle.write(text)


def main(argv=None):
    parser = argparse.ArgumentParser(
        prog="gen_android.py",
        description="Generate Android colour/dimension/style resources and launcher constants from ztmetro.tokens.json.",
        epilog="Example: python3 gen_android.py --out out/android",
    )
    parser.add_argument("--out", metavar="DIR", required=True,
                        help="output directory; res/values/*.xml, overlay/metro_overlay.xml and java/MetroTokens.java are written under it")
    parser.add_argument("--tokens", metavar="PATH", default=DEFAULT_TOKENS,
                        help="token file to read (default: ztmetro.tokens.json next to this script)")
    args = parser.parse_args(argv)

    tokens = load_tokens(args.tokens)
    problems = check_origins(tokens)
    if problems:
        sys.stderr.write("token provenance check failed:\n")
        for problem in problems:
            sys.stderr.write("  - %s\n" % problem)
        return 2
    out = args.out
    write_file(os.path.join(out, "res", "values", "metro_colors.xml"), emit_colors(tokens))
    write_file(os.path.join(out, "res", "values", "metro_dimens.xml"), emit_dimens(tokens))
    write_file(os.path.join(out, "res", "values", "metro_styles.xml"), emit_styles(tokens))
    write_file(os.path.join(out, "overlay", "metro_overlay.xml"), emit_overlay(tokens))
    write_file(os.path.join(out, "java", "MetroTokens.java"), emit_java(tokens))

    print("wrote %s/{res/values/metro_colors.xml,res/values/metro_dimens.xml,"
          "res/values/metro_styles.xml,overlay/metro_overlay.xml,java/MetroTokens.java}" % out)
    return 0


if __name__ == "__main__":
    sys.exit(main())
